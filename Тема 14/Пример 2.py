for x in '0123456789':
    x1 = int(f'98{x}79641', 22)
    x2 = int(f'25{x}49', 22)
    x3 = int(f'63{x}5', 22)
    res = x1 + x2 + x3
    if res % 21 == 0:
        print(res // 21)
        break

